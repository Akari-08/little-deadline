/** Validated sensor data. Missing/invalid measurements are null, never fabricated zeros. */
export type Vec3 = readonly [number, number, number];

export interface ImuReading {
  /** Initialization succeeded at boot; does not prove the sensor is still connected. */
  present: boolean;
  /** This reading is usable (device `valid` flag and all core fields in range). */
  valid: boolean;
  /** Device uptime (ms, uint32) of the sample. */
  sampleMs: number | null;
  /** m/s^2. */
  accel: Vec3 | null;
  /** rad/s (not deg/s). */
  gyro: Vec3 | null;
  /** MPU6050 chip temperature, not room temperature. */
  chipTemperatureC: number | null;
  /** Accelerometer gravity estimates; not fused orientation, no yaw. */
  rollDeg: number | null;
  pitchDeg: number | null;
}

export type EnvironmentKind = 'BME280' | 'BMP280' | 'none';

export interface EnvironmentReading {
  kind: EnvironmentKind;
  valid: boolean;
  sampleMs: number | null;
  temperatureC: number | null;
  /** Local absolute pressure; not sea-level corrected. */
  pressureHpa: number | null;
  /** Always null on BMP280 (it has no humidity sensor). */
  humidityPct: number | null;
}

export interface ButtonReading {
  /** GPIO13 button enabled in firmware (false in the supplied firmware). */
  enabled: boolean;
  pressed: boolean | null;
  /** Debounced press counter; wraps modulo 2^32. */
  pressCount: number | null;
}

export interface SensorMessage {
  seq: number | null;
  /** Device uptime in ms (uint32, wraps ~49.7 days); not UTC. */
  uptimeMs: number | null;
  imu: ImuReading;
  environment: EnvironmentReading;
  button: ButtonReading;
  display: { frames: number | null; lastFrameId: number | null };
  rssiDbm: number | null;
}

/**
 * live: fresh, valid physical reading. stale: last physical reading is too old (or the
 * device link is down). unavailable: sensor missing/invalid/unsupported.
 * simulated: generated by the app's hardware-free preview mode, not a physical reading.
 */
export type DataStatus = 'live' | 'stale' | 'unavailable' | 'simulated';
